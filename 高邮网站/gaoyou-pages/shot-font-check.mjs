import puppeteer from "puppeteer-core";
const EDGE = "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe";
const browser = await puppeteer.launch({ executablePath: EDGE, headless: "new", args: ["--no-sandbox"] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900, deviceScaleFactor: 1.5 });
await page.goto("http://localhost:8000/index.html?desktop=1", { waitUntil: "networkidle0", timeout: 45000 });
await new Promise(r => setTimeout(r, 2500));
await page.evaluate(() => document.fonts.ready.then(() => new Promise(r => setTimeout(r, 500))));
const box = await page.evaluate(() => { const h = document.querySelector(".hero h1"); const r = h.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, font: getComputedStyle(h).fontFamily }; });
console.log(JSON.stringify(box));
await page.screenshot({ path: "D:/新文科比赛/高邮网站/gaoyou-pages/screenshots/font-check-desktop.png", clip: { x: Math.max(0, box.x - 40), y: Math.max(0, box.y - 60), width: Math.min(1440, box.w + 80), height: box.h + 120 } });
const m = await browser.newPage();
await m.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
await m.goto("http://localhost:8000/index-m.html", { waitUntil: "networkidle0", timeout: 45000 });
await m.evaluate(() => document.fonts.ready.then(() => new Promise(r => setTimeout(r, 500))));
const mbox = await m.evaluate(() => { const h = document.querySelector(".hero h1"); const r = h.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, font: getComputedStyle(h).fontFamily }; });
console.log("mobile", JSON.stringify(mbox));
await m.screenshot({ path: "D:/新文科比赛/高邮网站/gaoyou-pages/screenshots/font-check-mobile.png", clip: { x: 0, y: 0, width: 390, height: 844 } });
await browser.close();
