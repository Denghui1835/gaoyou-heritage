import puppeteer from "puppeteer-core";
const EDGE = "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe";
const browser = await puppeteer.launch({ executablePath: EDGE, headless: "new", args: ["--no-sandbox"] });
const page = await browser.newPage();
await page.setViewport({ width: 1500, height: 1200, deviceScaleFactor: 2 });
await page.goto("file:///D:/新文科比赛/高邮网站/calligraphy/compare-fonts.html", { waitUntil: "networkidle0", timeout: 45000 });
await page.evaluate(() => document.fonts.ready.then(() => new Promise(r => setTimeout(r, 800))));
const h = await page.evaluate(() => document.body.scrollHeight);
await page.screenshot({ path: "D:/新文科比赛/高邮网站/calligraphy/compare-fonts.png", fullPage: true });
console.log("ok compare-fonts.png bodyHeight=" + h);
await browser.close();
